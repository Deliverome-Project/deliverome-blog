"""Release one post: a GitHub release that Zenodo archives as a citable code DOI.

Each published post gets its own release, tagged ``<slug>-v<version>``. The
GitHub-Zenodo integration archives every GitHub release as a new version of
this repo's Zenodo software record, using ``.zenodo.json`` for its metadata.
So the release flow is two steps, either side of a PR:

    uv run scripts/release_post.py prepare <slug>
        Writes .zenodo.json (title, authors from people.toml, version = tag,
        links to the Substack post and the CC0 data record). Commit it in the
        post's final PR with status = "published", and merge.

    uv run scripts/release_post.py tag <slug>            # dry run: all checks
    uv run scripts/release_post.py tag <slug> --execute  # creates the release
        On an up-to-date, clean main: re-checks the post, re-runs every figure
        script and requires byte-identical outputs, confirms every data URL in
        data/manifest.tsv downloads (so the Zenodo data record is published),
        then runs `gh release create`.

Afterwards, copy the version DOI from Zenodo into post.toml `code_doi` (PR).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "Deliverome-Project/deliverome-blog"
REPO_URL = f"https://github.com/{REPO}"


def sh(*args: str, cwd: Path = ROOT, check: bool = True) -> str:
    """Run a command, echoing it; return stdout."""
    print(f"$ {' '.join(args)}")
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"Failed ({result.returncode}):\n{result.stdout}{result.stderr}")
    return result.stdout.strip()


def load_post(slug: str) -> tuple[Path, dict, str]:
    post_dir = ROOT / "posts" / slug
    if not (post_dir / "post.toml").exists():
        sys.exit(f"No post at posts/{slug}")
    meta = tomllib.loads((post_dir / "post.toml").read_text())
    return post_dir, meta, f"{slug}-v{meta['version']}"


def creators(authors: list[str]) -> list[dict]:
    people = tomllib.loads((ROOT / "people.toml").read_text())
    missing = [a for a in authors if a not in people]
    if missing:
        sys.exit(f"Add {', '.join(missing)} to people.toml")
    return [
        {"name": people[a]["zenodo_name"], **{k: people[a][k] for k in ("affiliation", "orcid") if people[a].get(k)}}
        for a in authors
    ]


def prepare(slug: str) -> None:
    post_dir, meta, tag = load_post(slug)
    if meta["status"] != "published" or not meta["substack_url"] or not meta["published"]:
        sys.exit('Set status = "published", published, and substack_url in post.toml first')
    folder = f"{REPO_URL}/tree/{tag}/posts/{slug}"
    description = (
        f"<p>{meta['summary']}</p>"
        f'<p>Code, figure scripts and small data behind the Deliverome blog post '
        f'<a href="{meta["substack_url"]}"><em>{meta["title"]}</em></a>. '
        f'This post\'s files are in <a href="{folder}"><code>posts/{slug}/</code></a>; every figure '
        "is regenerated by a standalone script with <code>uv run</code>.</p>"
        "<p>Code is MIT; data we produce is CC0 1.0; text and figures are CC BY 4.0.</p>"
    )
    related = [{"identifier": meta["substack_url"], "relation": "isSupplementTo", "scheme": "url"}]
    if meta["data_doi"]:
        description += (
            f'<p>Large data: <a href="https://doi.org/{meta["data_doi"]}">{meta["data_doi"]}</a> (CC0 1.0).</p>'
        )
        related.append(
            {"identifier": meta["data_doi"], "relation": "isSupplementedBy", "resource_type": "dataset", "scheme": "doi"}
        )
    zenodo = {
        "upload_type": "software",
        "title": f"deliverome-blog: {meta['title']}",
        "description": description,
        "license": "mit",
        "access_right": "open",
        "version": tag,
        "language": "eng",
        "creators": creators(meta["authors"]),
        "keywords": ["Deliverome", "reproducible research", "open science"],
        "related_identifiers": related,
    }
    (ROOT / ".zenodo.json").write_text(json.dumps(zenodo, indent=2, ensure_ascii=False) + "\n")
    print(f"Wrote .zenodo.json for {tag}.")
    print("Next: commit it with the post's final changes, merge to main, then:")
    print(f"  uv run scripts/release_post.py tag {slug}")


def url_downloads(url: str) -> bool:
    req = urllib.request.Request(url, headers={"Range": "bytes=0-0"})
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            return response.status in (200, 206)
    except OSError:
        return False


def tag(slug: str, execute: bool) -> None:
    post_dir, meta, tag_name = load_post(slug)
    problems: list[str] = []

    if sh("git", "rev-parse", "--abbrev-ref", "HEAD") != "main":
        problems.append("not on main")
    if sh("git", "status", "--porcelain"):
        problems.append("working tree is not clean")
    sh("git", "fetch", "--tags", "origin")
    head = sh("git", "rev-parse", "HEAD")
    if head != sh("git", "rev-parse", "origin/main"):
        problems.append("main is not identical to origin/main")
    if sh("git", "tag", "--list", tag_name):
        problems.append(f"tag {tag_name} already exists; bump version in post.toml for a correction")
    if meta["status"] != "published":
        problems.append('post.toml status is not "published"')
    zenodo = json.loads((ROOT / ".zenodo.json").read_text()) if (ROOT / ".zenodo.json").exists() else {}
    if zenodo.get("version") != tag_name:
        problems.append(f".zenodo.json is not prepared for {tag_name}; run `prepare {slug}` and merge")
    if problems:
        sys.exit("Not releasing:\n  - " + "\n  - ".join(problems))

    sh("uv", "run", "scripts/build_index.py", "--check")
    sh("uv", "run", "--project", "shared", "blog-figure", "check", str(post_dir))
    for script in sorted((post_dir / "figures").glob("make_*.py")):
        sh("uv", "run", script.name, cwd=script.parent)
    changed = sh("git", "status", "--porcelain")
    if changed:
        sys.exit(f"Re-running the figure scripts changed committed files; commit them first:\n{changed}")

    manifest = post_dir / "data" / "manifest.tsv"
    urls = [line.split("\t")[1] for line in manifest.read_text().splitlines()[1:] if line.strip()]
    dead = [u for u in urls if not url_downloads(u)]
    if dead:
        sys.exit("These data URLs do not download (publish the Zenodo data record first):\n  " + "\n  ".join(dead))

    notes = (
        f"Code, figure scripts and data for **[{meta['title']}]({meta['substack_url']})** "
        f"({', '.join(meta['authors'])}).\n\n"
        f"- Post folder: [`posts/{slug}`]({REPO_URL}/tree/{tag_name}/posts/{slug})\n"
        + (f"- Data (CC0): https://doi.org/{meta['data_doi']}\n" if meta["data_doi"] else "")
        + "\nEvery figure regenerates with `uv run make_<name>.py` from the post's `figures/` folder."
    )
    command = ["gh", "release", "create", tag_name, "--target", head, "--title", f"{meta['title']} ({tag_name})"]
    if not execute:
        print(f"\nAll checks passed. Dry run; would run:\n  {' '.join(command)} --notes <notes>\n\n{notes}")
        print("\nRe-run with --execute to create the release.")
        return
    sh(*command, "--notes", notes)
    print(
        f"\nReleased {tag_name}. Zenodo archives it within minutes (if the GitHub integration is on).\n"
        f"Copy the version DOI into posts/{slug}/post.toml `code_doi`, run scripts/build_index.py, and open a PR."
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("prepare", help="write .zenodo.json for the post's release").add_argument("slug")
    tag_p = sub.add_parser("tag", help="check everything, then create the GitHub release")
    tag_p.add_argument("slug")
    tag_p.add_argument("--execute", action="store_true", help="actually create the release")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.slug)
    else:
        tag(args.slug, args.execute)


if __name__ == "__main__":
    main()
